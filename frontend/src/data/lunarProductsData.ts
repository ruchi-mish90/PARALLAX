export const getProductsForRegion = (regionId: string): LunarImageProduct[] => {
  return LUNAR_PRODUCTS.filter(p => p.regionId === regionId);
};

export const getProductById = (id: string): LunarImageProduct => {
  return LUNAR_PRODUCTS.find(p => p.id === id) || LUNAR_PRODUCTS[0];
};

export const getDefaultProductForInstrument = (
  instrument: string,
  regionId: string = 'faustini'
): LunarImageProduct => {
  const match = LUNAR_PRODUCTS.find(
    p => p.instrument === instrument && p.regionId === regionId
  );
  if (match) return match;
  return LUNAR_PRODUCTS.find(p => p.instrument === instrument) || LUNAR_PRODUCTS[0];
};
